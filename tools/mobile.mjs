import { chromium } from 'playwright';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const p = await b.newPage({ viewport:{width:390,height:844}, colorScheme:'light', isMobile:true, hasTouch:true, deviceScaleFactor:2 });
const errs=[]; p.on('pageerror', e=>errs.push('PAGEERROR '+e.message));
await p.goto('file://' + process.cwd() + '/Amiga-Constellation.html');
await p.waitForTimeout(1300);
console.log('h-scroll', JSON.stringify(await p.evaluate(()=>({dw:document.documentElement.scrollWidth,vw:innerWidth}))));
await p.click('#v-graph'); await p.waitForTimeout(1300);
await p.screenshot({ path:'/tmp/mm-graph.png' });
await p.evaluate(()=>{ const G=window.__GRAPH; const h=G.hubs.find(x=>(x.d&&x.d.label)==='Operating systems'); if(h) window.__lo(h); });
await p.waitForTimeout(600);
await p.screenshot({ path:'/tmp/mm-board.png' });
await p.click('#v-catalog'); await p.waitForTimeout(600);
await p.evaluate(()=>{const c=document.querySelector('.card'); if(c)c.click();});
await p.waitForTimeout(600);
await p.screenshot({ path:'/tmp/mm-drawer.png' });
console.log('h-scroll after', JSON.stringify(await p.evaluate(()=>({dw:document.documentElement.scrollWidth,vw:innerWidth}))));
console.log(errs.length?errs.join('\n'):'no errors');
await b.close();
